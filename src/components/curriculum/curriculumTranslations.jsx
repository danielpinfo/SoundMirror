function tr(map, lang, key) {
  if (!lang || lang === 'en') return key;
  return map?.[lang]?.[key] ?? key;
}

export function localizeCurriculum(lang = 'en') {
  // Shallow-clone top-level and deep map levels/lessons to avoid mutations
  return CURRICULUM.map((level) => ({
    ...level,
    title: tr(titles, lang, level.title),
    description: level.description ? tr({
      es: { 'Master individual vowels and consonants': 'Domina vocales y consonantes individuales' },
      it: { 'Master individual vowels and consonants': 'Impara vocali e consonanti singole' },
      pt: { 'Master individual vowels and consonants': 'Domine vogais e consoantes individuais' },
      de: { 'Master individual vowels and consonants': 'Lerne einzelne Vokale und Konsonanten' },
      fr: { 'Master individual vowels and consonants': 'Maîtrisez les voyelles et consonnes isolées' },
      ja: { 'Master individual vowels and consonants': '母音・子音の単音を習得' },
      zh: { 'Master individual vowels and consonants': '掌握单个元音和辅音' },
      hi: { 'Master individual vowels and consonants': 'एकल स्वर और व्यंजन में निपुण बनें' },
      ar: { 'Master individual vowels and consonants': 'إتقان الحروف المتحركة والساكنة المنفردة' },
    }, lang, level.description) : level.description,
    lessons: level.lessons.map((ls) => ({
      ...ls,
      label: ls.label ? tr(lessonLabels, lang, ls.label) : ls.label,
    })),
  }));
}
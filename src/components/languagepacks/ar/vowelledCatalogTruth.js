const ARABIC_MARKS = /[\u064B-\u0652\u0670]/g;
const ARABIC_MARK_PRESENT = /[\u064B-\u0652\u0670]/;

function normalizeExact(value = '') {
  return String(value || '')
    .normalize('NFC')
    .replace(/\u0640/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeBase(value = '') {
  return normalizeExact(value).replace(ARABIC_MARKS, '');
}

const entries = [];
const exactEntries = new Map();
const baseEntries = new Map();

for (const group of universal500) {
  const vowelledWords = ARABIC_VOWELLED_CATALOG_GROUPS[group.id];
  if (!Array.isArray(vowelledWords) || vowelledWords.length !== group.words.length) {
    throw new Error(`Arabic catalog truth length mismatch for ${group.id}`);
  }

  group.words.forEach((source, index) => {
    const entry = Object.freeze({
      id: `ar-catalog-${group.id}-${index + 1}`,
      source,
      vowelled: vowelledWords[index],
      groupId: group.id,
      index,
      register: 'msa-pausal',
      approval: 'multi-source-family-review',
    });
    const exact = normalizeExact(source);
    const base = normalizeBase(source);
    const existing = exactEntries.get(exact);

    if (existing && normalizeExact(existing.vowelled) !== normalizeExact(entry.vowelled)) {
      throw new Error(`Conflicting Arabic catalog truth for ${source}`);
    }

    entries.push(entry);
    exactEntries.set(exact, entry);
    // A partially marked catalog source (for example أَنْتِ versus أَنْتَ)
    // can share a bare spelling with another valid reading. Preserve it only
    // as an exact key; never make a marked form the fallback for bare input.
    if (!ARABIC_MARK_PRESENT.test(exact)) baseEntries.set(base, entry);
  });
}

export const ARABIC_VOWELLED_CATALOG_TRUTH = Object.freeze(entries);

export function getArabicVowelledCatalogTruth(value = '') {
  const exact = normalizeExact(value);
  if (!exact) return null;

  const exactEntry = exactEntries.get(exact);
  if (exactEntry) return exactEntry;
  if (ARABIC_MARK_PRESENT.test(exact)) return null;

  return baseEntries.get(normalizeBase(exact)) ?? null;
}

export default ARABIC_VOWELLED_CATALOG_TRUTH;

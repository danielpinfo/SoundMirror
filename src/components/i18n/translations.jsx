function readPath(source, keys) {
  let value = source;

  for (const key of keys) {
    value = value?.[key];
    if (value === undefined || value === null) return null;
  }

  return value;
}

function interpolate(value, params = {}) {
  if (typeof value !== 'string') return value;

  return value.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name)
      ? String(params[name])
      : match
  );
}

export const getLanguageCode = () => {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('soundmirror-language');
    if (stored) return stored;
  }
  return 'en';
};

export const setLanguageCode = (code) => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('soundmirror-language', code);
  }
};

export const t = (key, lang = 'en', params = {}) => {
  const keys = key.split('.');
  const localized =
    readPath(translations[lang], keys) ??
    readPath(uiMessages[lang], keys);
  const fallback =
    readPath(translations.en, keys) ??
    readPath(uiMessages.en, keys);

  return interpolate(localized ?? fallback ?? key, params);
};
